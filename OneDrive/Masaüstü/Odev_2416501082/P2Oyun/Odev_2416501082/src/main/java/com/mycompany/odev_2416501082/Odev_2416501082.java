         private void Oyunubaşlat() throws FileNotFoundException, IOException{
                panelkelimeler.removeAll();
                Hak = 0;
resimGuncelle();

    ArrayList<String> liste = new ArrayList<>();

    BufferedReader oku =
            new BufferedReader(
                    new FileReader(kelimeler));

    String satir;

    while((satir = oku.readLine()) != null){

        if(satir.length() >= 6){

            liste.add(satir);
        }
    }

    oku.close();

    Random rnd = new Random();

    secilenKelime =
            liste.get(
                    rnd.nextInt(liste.size())
            ).toUpperCase();

    int harfsayisi = secilenKelime.length();

    harfLabel = new JLabel[harfsayisi];

    panelkelimeler.setLayout(
            new FlowLayout(FlowLayout.LEFT)
    );

    for(int i=0;i<harfsayisi;i++){

        JLabel lbl = new JLabel("*");

        harfLabel[i] = lbl;

        panelkelimeler.add(lbl);
    }

    panelkelimeler.revalidate();

    panelkelimeler.repaint();

    Hak = 0;

    saniye = 0;

    lblresim.setIcon(null);

    if(timer != null){

        timer.stop();
    }

    timer = new Timer(1000, e -> {

        saniye++;

        lblsüre.setText(
                "Süre: "+saniye+" sn"
        );
    });

    timer.start();
        
        
         }
         
         
