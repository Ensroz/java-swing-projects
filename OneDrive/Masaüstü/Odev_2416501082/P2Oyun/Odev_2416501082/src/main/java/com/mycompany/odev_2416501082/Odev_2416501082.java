     private boolean SifrePaneli() throws IOException{
       
     
        if(!sifre.exists() ){
          
           String   yeni = JOptionPane.showInputDialog("Sifre giriniz:");
        this.setTitle(yeni);
        if(yeni==null){
            return false;
        }
                try{
       
FileWriter fw = new FileWriter(sifre);
fw.write(yeni);
fw.close();

JOptionPane.showMessageDialog(this,"Şifre başarıyla kaydedildi");
          }catch(IOException ex){
              JOptionPane.showMessageDialog(this,"Şifre kaydedilemedi:"+ex.getMessage());
              return false;
          }
        
        
        
        logYaz("Giriş: Yeni şifre başarıyla sisteme eklendi ve kaydedildi.");
        JOptionPane.showMessageDialog(null, "Şifreniz başarıyla eklendi! Şimdi giriş yapabilirsiniz.");
        }

        
        String kayitli="";
        try{
           BufferedReader oku = new
BufferedReader(new FileReader(sifre));
kayitli  = oku.readLine();
oku.close();
            
        }catch(IOException e){
            return false;
        }
        if(kayitli == null || kayitli.trim().isEmpty()){

    String yeni = JOptionPane.showInputDialog(
            null,
            "Yeni şifre oluşturunuz:");

    if(yeni == null || yeni.trim().isEmpty()){
        return false;
    }

    FileWriter fw = new FileWriter(sifre);

    fw.write(yeni);

    fw.close();

    kayitli = yeni;
}
       int hak=0;
       
       while(hak<3){
           JPasswordField passwordfield=new JPasswordField();
           int kalanhak=3-hak;
               int secim = JOptionPane.showConfirmDialog(
                null, 
            passwordfield, 
            "Sisteme Giriş Şifresi: (Kalan Hak:  " + kalanhak + ")  ", 
            JOptionPane.YES_NO_OPTION, 
            JOptionPane.PLAIN_MESSAGE
        );

        
        if (secim != JOptionPane.OK_OPTION) {
            
            logYaz("Giriş: Kullanıcı giriş ekranını iptal etti.");
            return false;
        }
        String girilen=new String(passwordfield.getPassword()).trim();
        kayitli=kayitli.trim();

        if(girilen.equals(kayitli)){
            
            logYaz("Başarılı giriş yapıldı.");
            return true;
        }
        else{
            hak++;
            logYaz("Hatalı mesaj girdiniz Kalan hak:" + (3-hak));
            JOptionPane.showMessageDialog(null, "Hatalı Şifre girdiniz!", "Hata", JOptionPane.ERROR_MESSAGE);
            
        }
                
        if(hak==3){
            JOptionPane.showMessageDialog(null, "Hak limitiniz doldu", "Hata", JOptionPane.ERROR_MESSAGE);
            return false;
        }
        
        
           
        
        
    }
            return false;
  
           
       }
