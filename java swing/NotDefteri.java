    private void jMenuItem2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItem2ActionPerformed
        // TODO add your handling code here:
    JFileChooser sec = new JFileChooser();

    int sonuc = sec.showSaveDialog(this);

    if (sonuc == JFileChooser.APPROVE_OPTION) {

        File dosya = sec.getSelectedFile();

        try (FileWriter fw = new FileWriter(dosya,true)) {

            fw.write(jTextArea1.getText()+"\t");

            JOptionPane.showMessageDialog(this, "Dosya başarıyla kaydedildi!");

        } catch (IOException e) {

            JOptionPane.showMessageDialog(this,
                    "Hata: " + e.getMessage());
        }
    }
        
        
        
    }//GEN-LAST:event_jMenuItem2ActionPerformed

    private void jMenuItem1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItem1ActionPerformed
        // TODO add your handling code here:
             JFileChooser dosyaSecimi = new JFileChooser();

        int sonuc = dosyaSecimi.showOpenDialog(this);

        if (sonuc == JFileChooser.APPROVE_OPTION) {

            File file = dosyaSecimi.getSelectedFile();

                 try {
                     BufferedReader oku=new BufferedReader(new FileReader(file));
                     String satir=oku.readLine();
                     while(satir!=null){
                         jTextArea2.append(satir+"\n");
                         satir=oku.readLine();
                     }
                     oku.close();
                     
                 } catch (FileNotFoundException ex) {
                     System.getLogger(NotDefteri.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
                 } catch (IOException ex) {
                     System.getLogger(NotDefteri.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
                 }

           
        
    } 
        
 
    }//GEN-LAST:event_jMenuItem1ActionPerformed

