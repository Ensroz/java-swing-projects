    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
    DefaultTableModel model1 =
            (DefaultTableModel) jTable1.getModel();

    DefaultTableModel model2 =
            (DefaultTableModel) jTable2.getModel();

    DefaultTableModel model3 =
            (DefaultTableModel) jTable3.getModel();

    int silinecek = jTable1.getSelectedRow();

    if (silinecek == -1) {
        JOptionPane.showMessageDialog(this,
                "Silmek istediğiniz öğrenciyi seçin!");
        return;
    }

    // Tablolardan sil
    model1.removeRow(silinecek);
    model2.removeRow(silinecek);
    model3.removeRow(silinecek);

    // Dosyayı baştan oluştur
    try (FileWriter fw = new FileWriter(dosya, false)) {

        for (int i = 0; i < model1.getRowCount(); i++) {

            fw.write(
                model1.getValueAt(i, 0) + "," +
                model1.getValueAt(i, 1) + "," +
                model1.getValueAt(i, 2) + "," +
                model1.getValueAt(i, 3) + "\n"
            );
        }

        JOptionPane.showMessageDialog(this,
                "Öğrenci başarıyla silindi!");

    } catch (IOException ex) {
        JOptionPane.showMessageDialog(this,
                "Dosya yazılırken hata oluştu!");
        ex.printStackTrace();
    }
        
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        int satir = jTable2.getSelectedRow();

    if (satir == -1) {
        JOptionPane.showMessageDialog(this,
                "Güncellenecek öğrenciyi seçin!");
        return;
    }

    DefaultTableModel model =
            (DefaultTableModel) jTable2.getModel();

    // Ad
    if (!jTextField3.getText().trim().isEmpty()) {
        model.setValueAt(
                jTextField3.getText().trim(),
                satir,
                0
        );
    }

    // Soyad
    if (!jTextField4.getText().trim().isEmpty()) {
        model.setValueAt(
                jTextField4.getText().trim(),
                satir,
                1
        );
    }

    // Cinsiyet
    if (!jTextField5.getText().trim().isEmpty()) {
        model.setValueAt(
                jTextField5.getText().trim(),
                satir,
                2
        );
    }

    // No
    model.setValueAt(
            String.valueOf(jComboBox3.getSelectedIndex() + 1),
            satir,
            3
    );

    // Dosyayı baştan yaz
    try {

        FileWriter fw = new FileWriter(dosya, false);

        for (int i = 0; i < model.getRowCount(); i++) {

            fw.write(
                    model.getValueAt(i, 0) + "," +
                    model.getValueAt(i, 1) + "," +
                    model.getValueAt(i, 2) + "," +
                    model.getValueAt(i, 3) + "\n"
            );
        }

        fw.close();

        JOptionPane.showMessageDialog(this,
                "Öğrenci başarıyla güncellendi.");

    } catch (IOException ex) {
        JOptionPane.showMessageDialog(this,
                "Dosya güncellenirken hata oluştu.");
        ex.printStackTrace();
    }


        
        
    }//GEN-LAST:event_jButton2ActionPerformed

