    public void stokAzalt(String urunAdi, int miktar) {
         String dosya="D:\\market.txt";

    ArrayList<String> satirlar = new ArrayList<>();

    try {
        BufferedReader br = new BufferedReader(new FileReader(dosya));

        String satir;

        while ((satir = br.readLine()) != null) {

            String[] parca = satir.split(":");

            String isim = parca[0];
            int stok = Integer.parseInt(parca[1]);

            if (isim.equals(urunAdi)) {

                if (stok < miktar) {
                    JOptionPane.showMessageDialog(this,
                            "Yeterli stok yok! Mevcut stok: " + stok);
                    br.close();
                    return;
                }

                stok = stok - miktar;
            }

            satirlar.add(isim+":"+stok);
        }

        br.close();

        BufferedWriter bw = new BufferedWriter(new FileWriter(dosya));

        for (String s : satirlar) {
            bw.write(s);
            bw.newLine();
        }

        bw.close();

    } catch (IOException | NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Dosya işlemi sırasında hata oluştu!");
    }
}
