    public void biletleriOku() throws FileNotFoundException, IOException{
            for (JButton btn : koltuklar) {
        btn.setBackground(Color.GREEN);
    }
        String film=jComboBox1.getSelectedItem().toString();
        String seans=jComboBox2.getSelectedItem().toString();
        
        BufferedReader oku=new BufferedReader(new FileReader(dosya));
       String satir;
        while( (satir=oku.readLine())!=null){
            String[] bilgiler=satir.split(";");
            if(film.equals(bilgiler[0]) && seans.equals(bilgiler[1]) ){
                 for(JButton btn : koltuklar){
                     if(btn.getText().equals(bilgiler[2])){
                         btn.setBackground(Color.RED);
                     }
                 }
            }
        }
        oku.close();
        
    }

